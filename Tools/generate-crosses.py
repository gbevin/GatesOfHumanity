#!/usr/bin/env python3
"""Extracts the names of the 192 Incarnation Crosses from the Global Incarnation Cross Index of
The Definitive Book of Human Design, and checks them against the geometry of the wheel.

Requires pdftotext. Only run it when the cross names need to change:

    Tools/generate-crosses.py "The Definitive Book Of Human Design.pdf" > src/main/resources/crosses.tsv
"""

import collections
import re
import subprocess
import sys

# the gates in increasing longitude, from gate 41 at 302 degrees
WHEEL = [41, 19, 13, 49, 30, 55, 37, 63, 22, 36, 25, 17, 21, 51, 42, 3, 27, 24, 2, 23, 8, 20, 16, 35, 45, 12,
         15, 52, 39, 53, 62, 56, 31, 33, 7, 4, 29, 59, 40, 64, 47, 6, 46, 18, 48, 57, 32, 50, 28, 44, 1, 43, 14,
         34, 9, 5, 26, 11, 10, 58, 38, 54, 61, 60]
POSITION = {gate: index for index, gate in enumerate(WHEEL)}
ANGLES = {'Right Angle': 'right', 'RightAngle': 'right', 'Juxtaposition': 'juxtaposition',
          'Left Angle': 'left', 'LeftAngle': 'left'}
# the offsets around the wheel of the Personality Earth, Design Sun and Design Earth gates
GEOMETRY = {'right': (32, 48, 16), 'juxtaposition': (32, 49, 17), 'left': (32, 49, 17)}
# how many gates share each name
SHARED = {'right': 4, 'juxtaposition': 1, 'left': 2}
# text recognition errors in the book's PDF, and the cross of gate 1, which the index writes without
# the hyphen that the gate and its own page have
CORRECTIONS = {'fension': 'Tension', 'the Explanation': 'Explanation', 'Self Expression': 'Self-Expression'}

# an entry can't run on into the next one, which starts with a bullet
ENTRY = re.compile(r"(Right ?Angle|Juxtaposition|Left ?Angle) Cross ?of ?([A-Za-z' ()\-0-9]+?)"
                   r"(?:\s*\(until \d+\))?\s*:[^\u2022]*?\(Gates? ?([0-9SOlI ,\-]+)\)")


def gate_numbers(text):
    numbers = []
    for token in re.split(r'[\s,-]+', text.strip()):
        if not token:
            continue
        value = int(token.replace('S', '5').replace('O', '0').replace('l', '1').replace('I', '1'))
        # a line break can drop the dash between two gates
        if value > 64 and len(token) > 2:
            for split in range(1, len(token)):
                first, second = int(token[:split]), int(token[split:])
                if 1 <= first <= 64 and 1 <= second <= 64:
                    numbers += [first, second]
                    break
            else:
                raise ValueError(f'{token} is not a gate')
        else:
            numbers.append(value)
    return numbers


def clean(name):
    name = re.sub(r'\s*\d+$', '', name.strip())
    name = re.sub(r'\bl(?=[a-z])', 'I', name)
    return CORRECTIONS.get(name, name)


def main():
    text = subprocess.run(['pdftotext', sys.argv[1], '-'], capture_output=True, text=True, check=True).stdout
    text = re.sub(r'\s+', ' ', text)
    index = text[text.index('QUARTER OF INITIATION - Theme'):]

    crosses = {}
    for angle_text, name, gates_text in ENTRY.findall(index):
        angle = ANGLES[angle_text]
        gates = gate_numbers(gates_text)
        if len(gates) != 4:
            sys.exit(f'The {angle} cross {name} has the gates {gates_text}, which are not four gates')
        key = (gates[0], angle)
        if key in crosses:
            continue
        offsets = tuple((POSITION[g] - POSITION[gates[0]]) % 64 for g in gates[1:])
        if offsets != GEOMETRY[angle]:
            sys.exit(f'Gate {gates[0]} {angle} {name} has the gates {gates}, which is not the geometry of its angle')
        crosses[key] = clean(name)

    missing = [(gate, angle) for gate in WHEEL for angle in GEOMETRY if (gate, angle) not in crosses]
    if missing:
        sys.exit(f'Missing crosses: {missing}')
    counts = collections.Counter((angle, name) for (gate, angle), name in crosses.items())
    for (angle, name), count in counts.items():
        if count != SHARED[angle]:
            sys.exit(f'The {angle} cross name {name!r} is used {count} times instead of {SHARED[angle]}')

    print('# The incarnation crosses by Personality Sun gate, from the Global Incarnation Cross Index of')
    print('# The Definitive Book of Human Design, generated by Tools/generate-crosses.py')
    print('# gate\tangle\tname')
    for gate in sorted(POSITION):
        for angle in ('right', 'juxtaposition', 'left'):
            print(f'{gate}\t{angle}\t{crosses[(gate, angle)]}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main()
