#!/usr/bin/env python3
"""Extracts the names of the 64 gates and of their hexagrams from The Definitive Book of Human Design.

Requires pdftotext. Only run it when the gate names need to change:

    Tools/generate-gates.py "The Definitive Book Of Human Design.pdf" > src/main/resources/gates.tsv
"""

import collections
import re
import subprocess
import sys

# the gate descriptions start with "GATE 41: DECREASE - THE GATE OF CONTRACTION"
HEADING = re.compile(r"GATE (\d{1,2}): ([A-Z][A-Za-z ()]+?) - +(?:THE GATE OF )?([A-Za-z/' -]+?)\s*$", re.MULTILINE)
SMALL_WORDS = {'the', 'of', 'in', 'at', 'on', 'to'}
# characters that the PDF's text recognition got wrong
FIXES = {'DIFFICULTV': 'DIFFICULTY'}
# the gates whose headings name them differently, with the names that the book uses in its text
CHOICES = {
    1: ('The Creative', 'Self-Expression'),
    9: ('The Taming Power of the Small', 'Focus'),
    20: ('Contemplation', 'the Now'),
    21: ('Biting Through', 'the Hunter/Huntress'),
    29: ('The Abysmal', 'Perseverance'),
    31: ('Influence', 'Influence'),
    57: ('The Gentle', 'Intuitive Clarity'),
    62: ('Preponderance of the Small', 'Details'),
}


def title(name, first_lower=False):
    words = []
    for i, word in enumerate(FIXES.get(w, w) for w in name.split()):
        word = '-'.join(part.capitalize() for part in word.split('-'))
        word = '/'.join(part[:1].upper() + part[1:] for part in word.split('/'))
        word = '('.join(part[:1].upper() + part[1:] for part in word.split('('))
        if word.lower() in SMALL_WORDS and (i > 0 or first_lower):
            word = word.lower()
        words.append(word)
    return ' '.join(words)


def main():
    text = subprocess.run(['pdftotext', '-layout', sys.argv[1], '-'], capture_output=True, text=True, check=True).stdout

    names = collections.defaultdict(set)
    for number, hexagram, name in HEADING.findall(text):
        names[int(number)].add((title(hexagram), title(name, first_lower=True)))

    if sorted(names) != list(range(1, 65)):
        sys.exit(f'Found {len(names)} gates instead of 64: {sorted(names)}')

    print('# The gate and hexagram names from The Definitive Book of Human Design, generated by Tools/generate-gates.py')
    print('# gate\thexagram\tname')
    for number in range(1, 65):
        candidates = names[number]
        if len(candidates) > 1:
            if CHOICES.get(number) not in candidates:
                sys.exit(f'Gate {number} has several names, choose one in CHOICES: {sorted(candidates)}')
            candidates = {CHOICES[number]}
        hexagram, name = candidates.pop()
        print(f'{number}\t{hexagram}\t{name}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main()
