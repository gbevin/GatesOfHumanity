#!/usr/bin/env python3
"""Extracts the names of the 36 channels from The Definitive Book of Human Design.

Requires pdftotext. Only run it when the channel names need to change:

    Tools/generate-channels.py "The Definitive Book Of Human Design.pdf" > src/main/resources/channels.tsv
"""

import re
import subprocess
import sys

# the channel descriptions start with "THE CHANNEL OF CHARISMA: 34 - 20 A Design where ..."
HEADING = re.compile(r"CHANNEL OF ([A-Z'\- ]{2,40}?): ?([0-9SOl]{1,2}) ?- ?([0-9SOl]{1,2}) ?A? ?Design")
# the circuit pages list their channels as "63 - 4 LOGIC"
CIRCUIT = re.compile(r"\b([0-9]{1,2}) - ([0-9]{1,2}) ([A-Z][A-Z'\- ]{2,30}?)\b(?= [0-9]| [A-Z][a-z])")
SMALL_WORDS = {'The', 'Of'}
# the heading of 58-18 is the only place where the book writes Judgement, its tables and its text have Judgment
SPELLINGS = {'Judgement': 'Judgment'}


def number(text):
    return int(text.replace('S', '5').replace('O', '0').replace('l', '1'))


def title(name):
    words = [w.capitalize() for w in name.replace("'", '').split()]
    return ' '.join(w.lower() if i == 0 and w in SMALL_WORDS else SPELLINGS.get(w, w) for i, w in enumerate(words))


def main():
    text = subprocess.run(['pdftotext', sys.argv[1], '-'], capture_output=True, text=True, check=True).stdout
    text = re.sub(r'\s+', ' ', text)

    channels = {}
    for name, first, second in HEADING.findall(text):
        gates = (number(first), number(second))
        channels.setdefault(frozenset(gates), (gates, title(name)))
    for first, second, name in CIRCUIT.findall(text):
        gates = (int(first), int(second))
        if frozenset(gates) not in channels and all(1 <= g <= 64 for g in gates) and name.strip():
            channels[frozenset(gates)] = (gates, title(name))

    if len(channels) != 36:
        sys.exit(f'Found {len(channels)} channels instead of 36: {sorted(v for v in channels.values())}')

    print('# The channel names from The Definitive Book of Human Design, generated by Tools/generate-channels.py')
    print('# gate\tgate\tname')
    for (first, second), name in sorted(channels.values()):
        print(f'{first}\t{second}\t{name}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main()
